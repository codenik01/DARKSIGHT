package ai

import "time"

// AITriageResult contains AI model evaluation for a specific finding.
type AITriageResult struct {
	ConfidenceScore   int       `json:"confidence_score"`   // 0 - 100%
	Summary           string    `json:"summary"`            // Concise technical breakdown
	FalsePositiveProb int       `json:"false_positive_prob"`// 0 - 100%
	ImpactAnalysis    string    `json:"impact_analysis"`    // Potential security impact
	RemediationSteps  []string  `json:"remediation_steps"`  // Actionable remediation steps
	ModelUsed         string    `json:"model_used"`         // Model identifier (e.g. model.gguf)
	EvaluatedAt       time.Time `json:"evaluated_at"`
}

// AITargetSummary contains executive security summary generated by the AI model.
type AITargetSummary struct {
	TargetDomain   string   `json:"target_domain"`
	ExecutiveSummary string `json:"executive_summary"`
	TopRisks       []string `json:"top_risks"`
	ActionPlan     []string `json:"action_plan"`
	OverallPosture string   `json:"overall_posture"` // Critical, High, Moderate, Strong
	ModelUsed      string   `json:"model_used"`
	GeneratedAt    time.Time `json:"generated_at"`
}
